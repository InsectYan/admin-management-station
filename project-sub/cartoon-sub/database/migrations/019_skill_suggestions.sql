CREATE TABLE IF NOT EXISTS cartoon_shot_bindings (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES cartoon_projects(id) ON DELETE CASCADE,
  shot_id INTEGER NOT NULL REFERENCES cartoon_shots(id) ON DELETE CASCADE,
  asset_id INTEGER NOT NULL REFERENCES cartoon_assets(id) ON DELETE CASCADE,
  reason VARCHAR(80) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cartoon_voice_cues (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES cartoon_projects(id) ON DELETE CASCADE,
  shot_id INTEGER NOT NULL REFERENCES cartoon_shots(id) ON DELETE CASCADE,
  text TEXT NOT NULL DEFAULT '',
  start_ms INTEGER NOT NULL DEFAULT 0,
  end_ms INTEGER NOT NULL DEFAULT 0,
  voice_key VARCHAR(80) NOT NULL DEFAULT '',
  media_ref VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cartoon_review_findings (
  id SERIAL PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES cartoon_projects(id) ON DELETE CASCADE,
  shot_id INTEGER REFERENCES cartoon_shots(id) ON DELETE SET NULL,
  rule_id INTEGER,
  level VARCHAR(16) NOT NULL DEFAULT 'warning',
  message TEXT NOT NULL DEFAULT '',
  node VARCHAR(32) NOT NULL DEFAULT 'script',
  source VARCHAR(16) NOT NULL DEFAULT 'model',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
